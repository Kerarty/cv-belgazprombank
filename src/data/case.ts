export type ReqKind = 'FR' | 'NFR' | 'CON';

export interface Requirement {
  id: string;
  kind: ReqKind;
  text: string;
}

export interface InterviewQuestion {
  id: string;
  /** Вопрос, который задаёт аналитик (игрок). */
  question: string;
  /** Ответ бизнес-заказчика. */
  answer: string;
  /** Какие требования вскрывает этот вопрос. */
  reveals: string[];
  /** Почему вопрос ценный (показывается после ответа). */
  why: string;
}

export interface AcceptanceScenario {
  id: string;
  /** Описание проверяемого сценария. */
  text: string;
  /** Истинный исход: соответствует ли сценарий требованиям. */
  actuallyPasses: boolean;
  /** Какое требование нарушено (только для дефектных сценариев). */
  violates?: string;
  /** Пояснение, показываемое после проверки. */
  explanation: string;
}

